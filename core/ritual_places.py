"""core/ritual_places.py — «места практики» как сигнал роутера Арканы.

Ритуалы фиксируют место в закрытом lookup ``ritual_place``
(migration 022e99f6431d): home / forest / field / water / crossroad /
graveyard / church / other — RU-лейблы Дома / Лес / Поле / Водоём /
Перекрёсток / Погост / Церковь / Другое.

Если сообщение упоминает такое место (в т.ч. разговорные синонимы:
кладбище/могила для «погоста», распутье для «перекрёстка», озеро/пруд/речка
для «водоёма», храм/часовня для «церкви», роща/чаща для «леса») — это
сильный сигнал что речь о практике, даже без слов «ритуал»/«работа».
Аркана НЕ должна редиректить такое в Nexus.

Исключены из сигнала два по своей природе неоднозначных места:
- «дом/дома» — «работа из дома» это Nexus (WFH), не практика;
- «поле» — «поле ввода», «минное поле» и т.п.
Их таксономия по-прежнему знает (парсер ритуала их подхватит из явного
контекста), но как эвристика роутера они шумят.
"""
from __future__ import annotations

import re

# Стемы канонических мест + разговорные синонимы. Границы слова, IGNORECASE.
_PLACE_HINT_RE = re.compile(
    r"\b("
    r"кладбищ\w*|погост\w*|могил\w*|"                 # graveyard
    r"перекрёстк\w*|перекрестк\w*|перекрёсток|перекресток|распуть\w*|"  # crossroad
    r"водоём\w*|водоем\w*|озер\w*|пруд\w*|речк\w*|"    # water
    r"церкв\w*|церковь|храм\w*|часовн\w*|"            # church
    r"рощ\w*|чащ\w*|опушк\w*|"                        # forest (colloquial)
    r"лесу|лесной\s+полян\w*"                         # forest («в лесу»; bare «лес» → «лестница», шум)
    r")\b",
    re.IGNORECASE,
)


def mentions_ritual_place(text: str) -> bool:
    """True если текст упоминает место практики (см. модульный docstring)."""
    return bool(_PLACE_HINT_RE.search(text or ""))
