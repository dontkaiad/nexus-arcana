"""core/ru_morph.py — минимальная РУ-морфология без внешних зависимостей.

Отсечение падежных окончаний по фиксированному списку суффиксов. Не полноценный
стеммер (нет проверки словаря, нет чередований в основе), но достаточно для
склонение-независимого сравнения коротких имён/названий: поиск по Памяти
(`core/memory.py`), матчинг имён долгов (#136).
"""
from __future__ import annotations

# Падежные окончания, длинные раньше коротких (важно: "ами" до "и").
_CASE_SUFFIXES = (
    "ами", "ями", "ого", "его", "ому", "ему", "ой", "ей",
    "ом", "ем", "ах", "ях", "ам", "ям", "ую", "юю",
    "ов", "ев", "ёв", "ий", "ый", "ая", "яя",
    "у", "ю", "а", "я", "е", "и", "ы", "о",
)

_MIN_STEM = 3


def strip_case_ending(word: str) -> str:
    """Убрать одно падежное окончание. Основа короче 3 символов не трогается
    (иначе «яма»→«я», «оля»→«ол» съедает слишком много)."""
    for suffix in _CASE_SUFFIXES:
        if word.endswith(suffix):
            stem = word[:-len(suffix)]
            if len(stem) >= _MIN_STEM:
                return stem
    return word


def normalize_phrase(text: str) -> str:
    """lower + пословное отсечение окончаний. Для склонение-независимого
    сравнения: `normalize_phrase("Ивану Петрову") == normalize_phrase("иван петров")`."""
    return " ".join(strip_case_ending(w) for w in text.lower().split())
