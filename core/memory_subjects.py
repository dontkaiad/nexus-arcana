def keyword_category(fact: str) -> Optional[str]:
    """Категория «Я» по ключевым словам или None (тогда решает Haiku). Порядок важен: первый сработавший.
    Коты (по имени/слову) → психиатрия/мании (Здоровье, не СДВГ) → практика (только с эзо-контекстом: «ритуал» сам
    по себе ничего не значит) → внешность → отношения → СДВГ → здоровье → работа → предпочтения → быт → паттерн.
    «депрессивный» в «любит/обожает …» — вкус, не здоровье."""
    raw = fact or ""
    t = raw.lower()
    if _CAT_NAMES.search(raw) or _CAT_WORDS.search(t):
        return CATS_CATEGORY
    if _PSYCH.search(t) and not (re.search(r"депресс", t) and _LIKES_CTX.search(t) and not re.search(r"мани|психиатр|диагноз|лекарств", t)):
        return "🏥 Здоровье"
    if _PRACTICE_STRICT.search(t) or ("ритуал" in t and _ESO_CTX.search(t)):
        return "🔮 Практика"
    for cat, rx in _COMPILED:
        if rx.search(t):
            return cat
    return None


# ── Фильтр рода: Кай пишет о себе в женском роде ────────────────────────────

_NOT_VERBS = {"канал", "финал", "стол", "угол", "стул", "вал", "зал", "металл", "портал", "терминал", "материал",
              "журнал", "идеал", "сигнал", "оригинал", "персонал", "ментал", "кристалл", "капитал", "хохол", "котёл",
              "посол", "осел", "козёл", "орёл", "осёл", "ствол", "иол", "вокал", "бокал", "фестиваль", "аналог", "ритуал", "ритуалы",
              "нравился", "понравился", "казался", "показался", "оказался"}
_MASC_PAST = re.compile(r"\b[а-яё]{2,}(?:ил|ыл|ал|ел|ул|ёл|ял|ол)(?:ся)?\b", _I)
_FEM_PAST = re.compile(r"\b[а-яё]+(?:ила|ыла|ала|ела|ула|ёла|яла|ола)(?:сь)?\b|\b[а-яё]+лась\b", _I)
_PRON_M = re.compile(r"\b(?:он|его|ему|него|нём|нем)\b", _I)
_INTERLOC = re.compile(r"собеседник", _I)
_MASC_EXTRA = re.compile(r"\b(?:был|мог|смог|помог|ушёл|ушел|пришёл|пришел|нашёл|нашел|шёл|вёл)\b", _I)


def male_signals(fact: str) -> List[str]:
    """Маркеры мужского рода в факте (Кай пишет о себе в женском). Пусто — не мужской. Женская форма прошедшего
    времени в том же факте снимает флаг глагола (смешанные тексты оставляем «Я»); местоимения/«Собеседник» — нет."""
    t = fact or ""
    out: List[str] = []
    verbs = [w for w in _MASC_PAST.findall(t) if w.lower() not in _NOT_VERBS and len(w) >= 4] + _MASC_EXTRA.findall(t)
    if verbs and not _FEM_PAST.search(t):
        out.append("глагол")
    if _PRON_M.search(t):
        out.append("он/его")
    if _INTERLOC.search(t):
        out.append("собеседник")
    return out


